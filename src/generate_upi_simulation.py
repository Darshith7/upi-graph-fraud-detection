"""Independent UPI transaction simulator used as a HELD-OUT test set (never used for training).

Why: every earlier number came from AMLSim, whose one fan-in shape (200 senders) and cycle shape the
model was trained on, and from challenge files generated by this project's own scripts. This module
is a separate generator with different assumptions, written to stress generalisation:

Normal behaviour (UPI-style)
  * P2P payments to a small personal contact list (lognormal amounts), diurnal pattern
  * merchant QR payments with Zipf-distributed merchant popularity (busy merchants = benign hubs)
  * biller payments, and payroll runs (one employer paying many employees on one day = benign fan-out)
  * hard NPCI-style limit: no single payment above INR 1,00,000
  * laundering amounts deliberately overlap the legitimate range (v1 used much larger amounts and a
    single feature separated the classes with AUC 0.98 - a shortcut; fixed once, not tuned to the model)

Laundering / mule typologies - NONE of these has the AMLSim shape the model was trained on
  1. collection_mule      8-80 victims pay one fresh account within ~1-2 days, which forwards >90%
  2. relay_chain          4-8 hop rapid layering with a small shave per hop
  3. structuring          one source splits INR 3-8 lakh into many sub-INR-50,000 payments to many mules
  4. circular_ring        4-7 accounts pass the same amount round 2-3 times
  5. fresh_account_scam   a new account gets small payments from 6-40 strangers, then sweeps out

Prevalence is ~0.8% (AMLSim is ~8%; real AML prevalence is lower still).
The simulator is the project authors' own model of UPI, so this is "independent of AMLSim", NOT
independent of the authors and NOT real data.  Output schema = data/amlsim_challenges/*.csv plus a
`typology` column used only for analysis (never as a model input).
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

PSPS = ["okhdfcbank", "oksbi", "okaxis", "okicici", "ybl", "paytm", "ibl", "upi"]
T0 = 1_735_689_600            # 2025-01-01 00:00:00 UTC
STEP_S = 7200                 # 2h steps, same time unit as the AMLSim data the model was trained on
MAX_AMOUNT = 100_000.0        # NPCI per-transaction limit (general UPI payments)

HOUR_W = np.array([1, 0.5, 0.3, 0.2, 0.3, 0.8, 2, 4, 6, 7, 7, 7, 7, 7, 6, 6, 6, 7, 8, 9, 9, 7, 4, 2], dtype=float)
HOUR_W /= HOUR_W.sum()


def generate(seed: int = 7, n_people: int = 20000, n_merchants: int = 700, n_billers: int = 60,
             n_payroll: int = 15, days: int = 14):
    rng = np.random.default_rng(seed)
    horizon = days * 86400
    scale = n_people / 20000.0                    # fraud campaigns scale with the population

    def n_campaigns(base: int) -> int:
        return max(1, int(round(base * scale)))
    people = np.arange(n_people)
    merchants = n_people + np.arange(n_merchants)
    billers = n_people + n_merchants + np.arange(n_billers)
    payroll = n_people + n_merchants + n_billers + np.arange(n_payroll)
    fresh_base = n_people + n_merchants + n_billers + n_payroll   # fresh (mule) accounts start here
    next_fresh = [fresh_base]

    def fresh(k=1):
        out = np.arange(next_fresh[0], next_fresh[0] + k)
        next_fresh[0] += k
        return out

    rows = []   # (ts, src, dst, amount, typology)

    def tx_times(n, lo, hi):
        """n timestamps in [lo, hi) following the diurnal profile."""
        base = rng.uniform(lo, hi, size=n)
        day = np.floor((base - T0) / 86400)
        hour = rng.choice(24, size=n, p=HOUR_W)
        return T0 + day * 86400 + hour * 3600 + rng.uniform(0, 3600, size=n)

    # ---------------------------------------------------------------- normal traffic
    contacts = [rng.choice(people, size=int(rng.integers(3, 11)), replace=False) for _ in range(n_people)]
    rate = rng.gamma(1.6, 0.55, size=n_people) * 1.2          # payments per day, mean ~1.05
    merch_p = 1.0 / np.arange(1, n_merchants + 1) ** 1.05
    merch_p /= merch_p.sum()
    for d in range(days):
        counts = rng.poisson(rate)
        for p in np.nonzero(counts)[0]:
            c = int(counts[p])
            ts = tx_times(c, T0 + d * 86400, T0 + (d + 1) * 86400)
            kind = rng.choice(4, size=c, p=[0.35, 0.55, 0.05, 0.05])   # contact / merchant / biller / new payee
            for t, k in zip(ts, kind):
                if k == 0:
                    dst = rng.choice(contacts[p])
                    amt = rng.uniform(5_000, 60_000) if rng.random() < 0.03 else rng.lognormal(np.log(500), 1.4)
                elif k == 1:
                    dst, amt = merchants[rng.choice(n_merchants, p=merch_p)], rng.lognormal(np.log(300), 1.0)
                elif k == 2:
                    dst, amt = rng.choice(billers), rng.lognormal(np.log(1200), 0.9)
                else:
                    dst = rng.choice(people)
                    amt = rng.uniform(5_000, 60_000) if rng.random() < 0.03 else rng.lognormal(np.log(600), 1.4)
                if dst != p:
                    rows.append((t, p, dst, amt, "normal"))
    # payroll runs: a benign high fan-out, one employer paying many employees on one day
    for emp in payroll:
        day = int(rng.integers(3, days - 1))
        staff = rng.choice(people, size=int(rng.integers(40, 120)), replace=False)
        t = T0 + day * 86400 + 9 * 3600 + np.sort(rng.uniform(0, 3600, size=len(staff)))
        for s, ti in zip(staff, t):
            rows.append((ti, emp, s, float(rng.uniform(15_000, 60_000)), "normal"))

    # ---------------------------------------------------------------- laundering typologies
    def when(lo_day=2):
        return T0 + rng.uniform(lo_day * 86400, (days - 2) * 86400)

    for _ in range(n_campaigns(20)):                                            # 1. collection mule
        mule, k = fresh(1)[0], int(rng.integers(8, 81))
        t = when() + np.sort(rng.exponential(6 * 3600, size=k))
        victims = rng.choice(people, size=k, replace=False)
        amts = np.clip(rng.lognormal(np.log(2_500), 1.0, size=k), 200, 49_999)
        for v, ti, a in zip(victims, t, amts):
            rows.append((ti, v, mule, a, "collection_mule"))
        out_t, drains = t.max() + rng.uniform(1800, 6 * 3600), fresh(int(rng.integers(1, 4)))
        for dd in drains:
            rows.append((out_t, mule, dd, min(MAX_AMOUNT, amts.sum() * 0.93 / len(drains)), "collection_mule"))
            out_t += rng.uniform(300, 3600)
    for _ in range(n_campaigns(15)):                                            # 2. relay chain
        hops, a, ti = int(rng.integers(4, 9)), float(np.clip(rng.lognormal(np.log(12_000), 1.0), 1_500, 90_000)), when()
        nodes = np.concatenate([[rng.choice(people)], fresh(hops)])
        for h in range(hops):
            rows.append((ti, nodes[h], nodes[h + 1], a, "relay_chain"))
            a *= rng.uniform(0.97, 0.99)
            ti += rng.uniform(300, 2400)
    for _ in range(n_campaigns(8)):                                             # 3. structuring below the limit
        src, total, ti = fresh(1)[0], float(rng.uniform(300_000, 800_000)), when()
        mules, parts = [], 0.0
        while parts < total:
            a = float(np.clip(rng.lognormal(np.log(14_000), 0.6), 5_000, 49_999))
            m = fresh(1)[0]
            mules.append(m)
            rows.append((ti, src, m, a, "structuring"))
            parts += a
            ti += rng.uniform(60, 1800)
        collector = fresh(1)[0]
        for m in mules:
            rows.append((ti + rng.uniform(600, 7200), m, collector, float(np.clip(rng.lognormal(np.log(12_000), 0.6), 4_000, 45_000)), "structuring"))
    for _ in range(n_campaigns(10)):                                            # 4. circular ring
        r, a, ti = int(rng.integers(4, 8)), float(np.clip(rng.lognormal(np.log(9_000), 1.0), 1_500, 60_000)), when()
        ring = fresh(r)
        for _round in range(int(rng.integers(2, 4))):
            for h in range(r):
                rows.append((ti, ring[h], ring[(h + 1) % r], a, "circular_ring"))
                ti += rng.uniform(600, 5400)
    for _ in range(n_campaigns(18)):                                            # 5. fresh-account scam burst
        scam, k, ti0 = fresh(1)[0], int(rng.integers(6, 41)), when()
        t = ti0 + np.sort(rng.uniform(0, 36 * 3600, size=k))
        for v, ti in zip(rng.choice(people, size=k, replace=False), t):
            rows.append((ti, v, scam, float(np.clip(rng.lognormal(np.log(800), 0.9), 100, 6_000)), "fresh_account_scam"))
        rows.append((t.max() + rng.uniform(900, 7200), scam, fresh(1)[0], float(np.clip(rng.lognormal(np.log(9_000), 0.9), 1_000, 40_000)), "fresh_account_scam"))

    df = pd.DataFrame(rows, columns=["timestamp_seconds", "sourceNodeId", "targetNodeId", "amount", "typology"])
    df = df[(df.timestamp_seconds >= T0) & (df.timestamp_seconds < T0 + horizon)].copy()
    df["amount"] = df["amount"].clip(1.0, MAX_AMOUNT).round(2)
    df = df.sort_values("timestamp_seconds", kind="mergesort").reset_index(drop=True)
    df["timestamp_seconds"] = df["timestamp_seconds"].astype(np.int64)
    df["timestamp_step"] = ((df["timestamp_seconds"] - T0) // STEP_S + 1).astype(int)
    df["transaction_id"] = np.arange(len(df)) + 5_000_000
    df["is_laundering"] = (df["typology"] != "normal").astype(int)
    for side, col in (("sender", "sourceNodeId"), ("receiver", "targetNodeId")):
        df[f"{side}_upi"] = [f"acc_{n:05d}@{PSPS[n % len(PSPS)]}" for n in df[col].values]
    return df[["transaction_id", "timestamp_seconds", "timestamp_step", "sender_upi", "receiver_upi",
               "sourceNodeId", "targetNodeId", "amount", "is_laundering", "typology"]]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--output", default="data/upi_holdout/upi_sim_holdout.csv")
    args = ap.parse_args()
    df = generate(seed=args.seed)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out, index=False)
    print(f"Wrote {len(df):,} transactions to {out}: laundering {df.is_laundering.sum():,} ({df.is_laundering.mean():.2%}), "
          f"accounts {len(set(df.sourceNodeId) | set(df.targetNodeId)):,}, steps {df.timestamp_step.max()}, "
          f"max amount {df.amount.max():,.0f}")
    print(df.groupby("typology").size().to_string())


if __name__ == "__main__":
    main()
